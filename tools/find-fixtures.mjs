/** Quote a string as a single-quoted TypeScript literal. */
function quote(value) {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
}

/** Format a fixture value in the repository's prettier-like style. */
function formatValue(value, indent = 0) {
  const pad = ' '.repeat(indent)
  const childPad = ' '.repeat(indent + 2)

  if (value === null) return 'null'
  if (typeof value === 'string') return quote(value)
  if (typeof value === 'number' || typeof value === 'boolean') return String(value)

  if (Array.isArray(value)) {
    if (value.length === 0) return '[]'
    const items = value.map((item) => `${childPad}${formatValue(item, indent + 2)},`)
    return `[\n${items.join('\n')}\n${pad}]`
  }

  if (typeof value === 'object') {
    const entries = Object.entries(value)
    if (entries.length === 0) return '{}'
    const lines = entries.map(
      ([key, item]) => `${childPad}${key}: ${formatValue(item, indent + 2)},`,
    )
    return `{\n${lines.join('\n')}\n${pad}}`
  }

  throw new Error(`Cannot format value of type ${typeof value}`)
}

async function loadEngine() {
  const server = await createServer({
    root: repoRoot,
    configFile: false,
    server: { middlewareMode: true },
    appType: 'custom',
    logLevel: 'error',
  })

  try {
    const load = await server.ssrLoadModule('/src/data/load.ts')
    const fusion = await server.ssrLoadModule('/src/engine/fusion.ts')
    const recipesModule = await server.ssrLoadModule('/src/engine/recipes.ts')
    const reach = await server.ssrLoadModule('/src/engine/reach.ts')
    const inheritance = await server.ssrLoadModule('/src/engine/inheritance.ts')
    const rules = await server.ssrLoadModule('/src/engine/rules.ts')

    const data = load.loadGameData({ ownedDlc: [] })
    const recipes = recipesModule.buildRecipeIndex(
      data,
      fusion.createFusion(data, { allowRare: false }),
      null,
    )

    return { data, recipes, reach, inheritance, rules }
  } finally {
    await server.close()
  }
}

function createFixtureContext({ data, recipes, reach, inheritance, rules }) {
  const personaByName = new Map(data.personas.map((persona) => [persona.name, persona]))
  const skillByName = new Map(data.skills.map((skill) => [skill.name, skill]))

  const reachCache = new Map()
  const traitCache = new Map()

  function persona(name) {
    return personaByName.get(name)
  }

  function skill(name) {
    return skillByName.get(name)
  }

  function learns(name, skillName) {
    const entry = persona(name)
    return entry !== undefined && Object.hasOwn(entry.skills, skillName)
  }

  function nonUnique(skillName) {
    const entry = skill(skillName)
    return entry !== undefined && !entry.unique
  }

  function inheritable(target, skillName) {
    return inheritance.canInherit(data, target, skillName)
  }

  function distance(skillName, source, target) {
    const key = `${skillName}\u0000${source}`
    let map = reachCache.get(key)
    if (!map) {
      map = reach.skillReach(data, recipes, skillName, source)
      reachCache.set(key, map)
    }
    return map.get(target)
  }

  function reachable(skillName, source, target) {
    return distance(skillName, source, target) !== undefined
  }

  function traitDistance(source, target) {
    let map = traitCache.get(source)
    if (!map) {
      map = reach.traitReach(data, recipes, source)
      traitCache.set(source, map)
    }
    return map.get(target)
  }

  function recipesFor(target) {
    return recipes.get(target) ?? []
  }

  function hasRecipeWithBoth(target, first, second) {
    return recipesFor(target).some(
      (recipe) =>
        recipe.ingredients.includes(first) && recipe.ingredients.includes(second),
    )
  }

  function partnerCount(target, source) {
    const partners = new Set()
    for (const recipe of recipesFor(target)) {
      if (!recipe.ingredients.includes(source)) continue
      for (const ingredient of recipe.ingredients) {
        if (ingredient !== source) partners.add(ingredient)
      }
    }
    return partners.size
  }

  const validators = {
    DIRECT(f) {
      return (
        persona(f.target) !== undefined &&
        persona(f.source) !== undefined &&
        nonUnique(f.skill) &&
        learns(f.source, f.skill) &&
        distance(f.skill, f.source, f.target) === 1
      )
    },

    TWO_STEP(f) {
      return (
        persona(f.target) !== undefined &&
        persona(f.source) !== undefined &&
        nonUnique(f.skill) &&
        learns(f.source, f.skill) &&
        distance(f.skill, f.source, f.target) === 2
      )
    },

    HELD_DIRECT(f) {
      return (
        persona(f.target) !== undefined &&
        persona(f.source) !== undefined &&
        recipesFor(f.target).some((recipe) =>
          recipe.ingredients.includes(f.source),
        ) &&
        !learns(f.source, f.skill) &&
        nonUnique(f.skill) &&
        inheritable(f.target, f.skill)
      )
    },

    TWO_SOURCES_ONE_RECIPE(f) {
      return (
        f.a.skill !== f.b.skill &&
        hasRecipeWithBoth(f.target, f.a.source, f.b.source) &&
        learns(f.a.source, f.a.skill) &&
        learns(f.b.source, f.b.skill) &&
        nonUnique(f.a.skill) &&
        nonUnique(f.b.skill) &&
        inheritable(f.target, f.a.skill) &&
        inheritable(f.target, f.b.skill)
      )
    },

    SAME_SOURCE_TWO_SKILLS(f) {
      if (!Array.isArray(f.skills) || f.skills.length !== 2) return false
      if (f.skills[0] === f.skills[1]) return false
      return f.skills.every(
        (skillName) =>
          learns(f.source, skillName) &&
          distance(skillName, f.source, f.target) === 1,
      )
    },

    SOURCE_MUST_CARRY(f) {
      return (
        recipesFor(f.target).some((recipe) =>
          recipe.ingredients.includes(f.a.source),
        ) &&
        distance(f.b.skill, f.b.source, f.a.source) === 1 &&
        learns(f.b.source, f.b.skill) &&
        learns(f.a.source, f.a.skill) &&
        inheritable(f.target, f.a.skill) &&
        inheritable(f.target, f.b.skill)
      )
    },

    OVER_CAPACITY(f) {
      if (!Array.isArray(f.skills)) return false
      const skills = f.skills.map((pair) => pair.skill)
      if (new Set(skills).size !== skills.length) return false
      return (
        f.skills.length > inheritance.inheritCapacity(data, f.target, 2) &&
        f.skills.every(
          (pair) =>
            learns(pair.source, pair.skill) &&
            inheritable(f.target, pair.skill) &&
            reachable(pair.skill, pair.source, f.target),
        )
      )
    },

    TRAIT_DIRECT(f) {
      const source = persona(f.source)
      return (
        source !== undefined &&
        source.trait === f.trait &&
        traitDistance(f.source, f.target) === 1
      )
    },

    ADVANCED_ONE(f) {
      return (
        f.target === 'Neko Shogun' &&
        f.source === 'Kodama' &&
        learns(f.source, f.skill) &&
        distance(f.skill, f.source, f.target) === 1
      )
    },

    ADVANCED_TWO(f) {
      return (
        f.target === 'Neko Shogun' &&
        f.a.source === 'Kodama' &&
        f.b.source === 'Sudama' &&
        learns(f.a.source, f.a.skill) &&
        learns(f.b.source, f.b.skill) &&
        distance(f.a.skill, f.a.source, f.target) === 1 &&
        distance(f.b.skill, f.b.source, f.target) === 1
      )
    },

    MANY_RECIPES(f) {
      return (
        learns(f.source, f.skill) &&
        distance(f.skill, f.source, f.target) === 1 &&
        partnerCount(f.target, f.source) >= 5
      )
    },

    SIX_SKILLS(f) {
      if (!Array.isArray(f.skills) || f.skills.length !== 6) return false
      const sources = f.skills.map((pair) => pair.source)
      if (new Set(sources).size !== sources.length) return false
      const skillNames = f.skills.map((pair) => pair.skill)
      if (new Set(skillNames).size !== skillNames.length) return false

      const everyPairValid = f.skills.every(
        (pair) =>
          learns(pair.source, pair.skill) &&
          inheritable(f.target, pair.skill) &&
          reachable(pair.skill, pair.source, f.target),
      )
      if (!everyPairValid) return false

      const recipe = recipesFor(f.target).find((candidate) =>
        sources.every((source) => candidate.ingredients.includes(source)),
      )
      if (!recipe) return false
      return inheritance.inheritCapacity(data, f.target, recipe.ingredients.length) >= 6
    },

    UNREACHABLE(f) {
      return (
        persona(f.source) !== undefined &&
        learns(f.source, f.skill) &&
        inheritable(f.target, f.skill) &&
        !reachable(f.skill, f.source, f.target)
      )
    },
  }

  function validSkillsFor(target, source) {
    const entry = persona(source)
    if (!entry) return []
    return Object.keys(entry.skills).filter(
      (skillName) => nonUnique(skillName) && inheritable(target, skillName),
    )
  }

  function firstValidSkill(target, source) {
    return validSkillsFor(target, source)[0] ?? null
  }

  const searches = {
    DIRECT() {
      for (const target of data.personas) {
        for (const recipe of recipesFor(target.name)) {
          for (const source of recipe.ingredients) {
            if (source === target.name) continue
            const skillName = firstValidSkill(target.name, source)
            if (skillName === null) continue
            const fixture = { target: target.name, skill: skillName, source }
            if (validators.DIRECT(fixture)) return fixture
          }
        }
      }
      return null
    },

    TWO_STEP() {
      for (const target of data.personas) {
        for (const targetRecipe of recipesFor(target.name)) {
          for (const middle of targetRecipe.ingredients) {
            if (middle === target.name) continue
            for (const middleRecipe of recipesFor(middle)) {
              for (const source of middleRecipe.ingredients) {
                if (source === middle) continue
                const entry = persona(source)
                if (!entry) continue
                for (const skillName of Object.keys(entry.skills)) {
                  if (!nonUnique(skillName)) continue
                  if (!inheritable(middle, skillName)) continue
                  if (!inheritable(target.name, skillName)) continue
                  const fixture = { target: target.name, skill: skillName, source }
                  if (validators.TWO_STEP(fixture)) return fixture
                }
              }
            }
          }
        }
      }
      return null
    },

    HELD_DIRECT() {
      for (const target of data.personas) {
        for (const recipe of recipesFor(target.name)) {
          for (const source of recipe.ingredients) {
            for (const skillEntry of data.skills) {
              const skillName = skillEntry.name
              if (skillEntry.unique) continue
              if (learns(source, skillName)) continue
              if (!inheritable(target.name, skillName)) continue
              const fixture = { target: target.name, skill: skillName, source }
              if (validators.HELD_DIRECT(fixture)) return fixture
            }
          }
        }
      }
      return null
    },

    TWO_SOURCES_ONE_RECIPE() {
      for (const target of data.personas) {
        for (const recipe of recipesFor(target.name)) {
          const ingredients = [...new Set(recipe.ingredients)]
          for (let a = 0; a < ingredients.length; a += 1) {
            for (let b = a + 1; b < ingredients.length; b += 1) {
              const aSkills = validSkillsFor(target.name, ingredients[a])
              const bSkills = validSkillsFor(target.name, ingredients[b])
              for (const aSkill of aSkills) {
                for (const bSkill of bSkills) {
                  if (aSkill === bSkill) continue
                  const fixture = {
                    target: target.name,
                    a: { skill: aSkill, source: ingredients[a] },
                    b: { skill: bSkill, source: ingredients[b] },
                  }
                  if (validators.TWO_SOURCES_ONE_RECIPE(fixture)) return fixture
                }
              }
            }
          }
        }
      }
      return null
    },

    SAME_SOURCE_TWO_SKILLS() {
      for (const target of data.personas) {
        for (const recipe of recipesFor(target.name)) {
          for (const source of recipe.ingredients) {
            const entry = persona(source)
            if (!entry) continue
            const validSkills = Object.keys(entry.skills).filter(
              (skillName) =>
                nonUnique(skillName) &&
                inheritable(target.name, skillName) &&
                distance(skillName, source, target.name) === 1,
            )
            if (validSkills.length < 2) continue
            const fixture = {
              target: target.name,
              source,
              skills: [validSkills[0], validSkills[1]],
            }
            if (validators.SAME_SOURCE_TWO_SKILLS(fixture)) return fixture
          }
        }
      }
      return null
    },

    SOURCE_MUST_CARRY() {
      for (const target of data.personas) {
        for (const targetRecipe of recipesFor(target.name)) {
          for (const aSource of targetRecipe.ingredients) {
            const aSkill = firstValidSkill(target.name, aSource)
            if (aSkill === null) continue
            for (const aRecipe of recipesFor(aSource)) {
              for (const bSource of aRecipe.ingredients) {
                if (bSource === aSource) continue
                const bEntry = persona(bSource)
                if (!bEntry) continue
                for (const bSkill of Object.keys(bEntry.skills)) {
                  if (!nonUnique(bSkill)) continue
                  if (!inheritable(aSource, bSkill)) continue
                  if (!inheritable(target.name, bSkill)) continue
                  const fixture = {
                    target: target.name,
                    a: { skill: aSkill, source: aSource },
                    b: { skill: bSkill, source: bSource },
                  }
                  if (validators.SOURCE_MUST_CARRY(fixture)) return fixture
                }
              }
            }
          }
        }
      }
      return null
    },

    OVER_CAPACITY() {
      for (const target of data.personas) {
        const needed = inheritance.inheritCapacity(data, target.name, 2) + 1
        const picks = []
        for (const skillEntry of data.skills) {
          if (skillEntry.unique) continue
          if (!inheritable(target.name, skillEntry.name)) continue
          let source = null
          for (const candidate of Object.keys(skillEntry.personas)) {
            if (!persona(candidate)) continue
            if (reachable(skillEntry.name, candidate, target.name)) {
              source = candidate
              break
            }
          }
          if (source === null) continue
          picks.push({ skill: skillEntry.name, source })
          if (picks.length >= needed) break
        }
        if (picks.length < needed) continue
        const fixture = { target: target.name, skills: picks }
        if (validators.OVER_CAPACITY(fixture)) return fixture
      }
      return null
    },

    TRAIT_DIRECT() {
      for (const target of data.personas) {
        for (const recipe of recipesFor(target.name)) {
          for (const source of recipe.ingredients) {
            const entry = persona(source)
            if (!entry || !rules.canPassTrait(entry) || !entry.trait) continue
            if (traitDistance(source, target.name) !== 1) continue
            const fixture = {
              target: target.name,
              trait: entry.trait,
              source,
            }
            if (validators.TRAIT_DIRECT(fixture)) return fixture
          }
        }
      }
      return null
    },

    ADVANCED_ONE() {
      const target = 'Neko Shogun'
      const source = 'Kodama'
      const entry = persona(source)
      if (!entry) return null
      for (const skillName of Object.keys(entry.skills)) {
        const fixture = { target, skill: skillName, source }
        if (validators.ADVANCED_ONE(fixture)) return fixture
      }
      return null
    },

    ADVANCED_TWO() {
      const target = 'Neko Shogun'
      const aSource = 'Kodama'
      const bSource = 'Sudama'
      const aEntry = persona(aSource)
      const bEntry = persona(bSource)
      if (!aEntry || !bEntry) return null
      const aSkills = Object.keys(aEntry.skills).filter(
        (skillName) => distance(skillName, aSource, target) === 1,
      )
      const bSkills = Object.keys(bEntry.skills).filter(
        (skillName) => distance(skillName, bSource, target) === 1,
      )
      for (const aSkill of aSkills) {
        for (const bSkill of bSkills) {
          const fixture = {
            target,
            a: { skill: aSkill, source: aSource },
            b: { skill: bSkill, source: bSource },
          }
          if (validators.ADVANCED_TWO(fixture)) return fixture
        }
      }
      return null
    },

    MANY_RECIPES() {
      for (const target of data.personas) {
        for (const recipe of recipesFor(target.name)) {
          for (const source of recipe.ingredients) {
            if (partnerCount(target.name, source) < 5) continue
            const skillName = firstValidSkill(target.name, source)
            if (skillName === null) continue
            const fixture = { target: target.name, skill: skillName, source }
            if (validators.MANY_RECIPES(fixture)) return fixture
          }
        }
      }
      return null
    },

    // Deliberately null: see NULL_COMMENTS. No no-DLC build exists under the
    // natural "special persona unavoidable on every route" interpretation.
    ADVANCED_INTERMEDIATE() {
      return null
    },

    SIX_SKILLS() {
      for (const target of data.personas) {
        for (const recipe of recipesFor(target.name)) {
          const capacity = inheritance.inheritCapacity(
            data,
            target.name,
            recipe.ingredients.length,
          )
          if (capacity < 6) continue
          const sources = [...new Set(recipe.ingredients)]
          if (sources.length < 6) continue

          const picks = []
          const usedSkills = new Set()
          for (const source of sources) {
            const skillName = validSkillsFor(target.name, source).find(
              (candidate) =>
                !usedSkills.has(candidate) &&
                distance(candidate, source, target.name) !== undefined,
            )
            if (skillName === undefined) continue
            usedSkills.add(skillName)
            picks.push({ skill: skillName, source })
            if (picks.length === 6) break
          }
          if (picks.length < 6) continue

          const fixture = { target: target.name, skills: picks }
          if (validators.SIX_SKILLS(fixture)) return fixture
        }
      }
      return null
    },

    UNREACHABLE() {
      for (const target of data.personas) {
        for (const skillEntry of data.skills) {
          if (skillEntry.unique) continue
          if (!inheritable(target.name, skillEntry.name)) continue
          for (const source of Object.keys(skillEntry.personas)) {
            if (!persona(source)) continue
            if (reachable(skillEntry.name, source, target.name)) continue
            const fixture = {
              target: target.name,
              skill: skillEntry.name,
              source,
            }
            if (validators.UNREACHABLE(fixture)) return fixture
          }
        }
      }
      return null
    },
  }

  return { validators, searches }
}

function resolveFixture(name, { validators, searches }) {
  const candidate = CANDIDATES[name]

  if (candidate !== null && candidate !== undefined) {
    if (validators[name](candidate)) return candidate
    const fallback = searches[name]()
    if (fallback !== null) return fallback
    throw new Error(
      `Curated ${name} fixture no longer satisfies its definition and no fallback was found`,
    )
  }

  const fallback = searches[name]()
  if (fallback !== null) return fallback
  return null
}

function renderFixture(name, value) {
  const lines = []
  const comment = value === null ? NULL_COMMENTS[name] : undefined
  if (comment) {
    for (const line of comment) lines.push(`// ${line}`)
  }
  const typeName = FIXTURE_TYPES[name]
  lines.push(`export const ${name}: ${typeName} | null = ${formatValue(value)}`)
  return lines.join('\n')
}

function renderFile(fixtures) {
  const blocks = [HEADER, '', TYPE_BLOCK]
  for (const name of FIXTURE_ORDER) {
    blocks.push('', renderFixture(name, fixtures[name]))
  }
  return `${blocks.join('\n')}\n`
}

async function main() {
  const engine = await loadEngine()
  const context = createFixtureContext(engine)

  const fixtures = {}
  for (const name of FIXTURE_ORDER) {
    fixtures[name] = resolveFixture(name, context)
  }

  const output = renderFile(fixtures)
  mkdirSync(dirname(outputPath), { recursive: true })
  writeFileSync(outputPath, output, 'utf8')

  console.log('Generated tests/helpers/fixtures.ts')
  for (const name of FIXTURE_ORDER) {
    const value = fixtures[name]
    if (value === null) {
      console.log(`  ${name}: null`)
    } else if ('target' in value) {
      console.log(`  ${name}: ${value.target}`)
    } else {
      console.log(`  ${name}: set`)
    }
  }
}

try {
  await main()
} catch (error) {
  console.error(
    `\nfind-fixtures failed: ${error instanceof Error ? error.message : String(error)}`,
  )
  process.exitCode = 1
}
